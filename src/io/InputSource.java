package io;
/**
 * интерфейс для источников ввода данных
 * его реализуют классы которые получают данные из консоли или из скрипта
 */
public interface InputSource {
     /**
      * считывает следующую строку из источника ввода
      * @return следующая строка или null если ввод закончился
      */
     String nextLine ();
     /**
      * выводит подсказку для пользователя перед вводом поля
      * @param fieldNAme название поля которое нужно ввести
      */
     void  clue(String fieldNAme);

}
/*
этот интерфейс задает общий способ получения информации и выводы подсказок

метод nextLine нужен для того, чтобы возвращать следующую строку ввода

метод clue нужен для вывода подсказок
 */